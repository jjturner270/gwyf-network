<#
.SYNOPSIS
  Builds GWYF-Community-Setup.exe: the one-click installer that finds the game,
  installs BepInEx + the observer mod, and knows how to uninstall.

.DESCRIPTION
  Pipeline:
    1. Build the mod release package (reuses package-mod.ps1, needs GWYF_REFS
       pointing at the game's BepInEx/interop references).
    2. Embed the resulting mod zip into the setup exe as a resource.
    3. Bake the community API endpoint into the exe.
    4. Build the net48 WinForms setup exe (self-contained, runs on any
       Windows 10/11 without installing anything).
    5. Emit dist/GWYF-Community-Setup-<version>.exe + SHA-256, run the headless
       selftest against the artifact.

  Endpoint guardrail: a release build must NOT bake a loopback endpoint. Pass
  -IngestUrl https://… for real distributions; pass -AllowLoopback only for
  local dev/test builds. Shipped builds point at the real API or the pipeline
  refuses to build them.

  The user-facing promise is: double-click, press Install, press Launch.
  Nothing else.
#>
[CmdletBinding()]
param(
    [string]$GwyfRefs = $env:GWYF_REFS,
    [string]$IngestUrl = "http://127.0.0.1:3000",
    [switch]$AllowLoopback,
    [string]$Version = "0.3.0",
    [string]$OutDir = (Join-Path (Resolve-Path (Join-Path $PSScriptRoot "..")).Path "dist")
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrWhiteSpace($GwyfRefs) -or -not (Test-Path -LiteralPath $GwyfRefs)) {
    throw "GWYF_REFS must point at the game's interop references (BepInEx/interop). Set GWYF_REFS or pass -GwyfRefs."
}

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$setupProject = Join-Path $repoRoot "installer\GWYFCommunityNetwork.Setup\GWYFCommunityNetwork.Setup.csproj"

# ---- endpoint guardrail: never ship a loopback bake by accident -------------
$endpoint = $IngestUrl
$ep = $null
if ([Uri]::TryCreate($endpoint, [UriKind]::Absolute, [ref]$ep)) {
    if ($ep.IsLoopback -and -not $AllowLoopback) {
        throw "refusing to bake loopback endpoint '$endpoint' into a $Version build. " +
              "Pass -IngestUrl https://api.… for a real release, or -AllowLoopback for a local dev build."
    }
    if ($ep.Scheme -notin @("http", "https")) {
        throw "unsupported endpoint scheme '$($ep.Scheme)' in '$endpoint' (http/https only)."
    }
} else {
    throw "IngestUrl is not a valid absolute URL: '$endpoint'"
}

$generatedDir = Join-Path $repoRoot "installer\GWYFCommunityNetwork.Setup\Generated"
New-Item -ItemType Directory -Force -Path $generatedDir | Out-Null
$bakedEndpoint = $endpoint.Replace("\", "\\").Replace('"', '\"')
@"
namespace GwyfCommunity.Setup;

// Auto-generated by scripts/build-setup.ps1; not committed. The release build
// bakes the ingest endpoint so a normal user never touches configuration.
internal static partial class BuildInfo
{
    public const string IngestBaseUrl = "$bakedEndpoint";
}
"@ | Set-Content -Path (Join-Path $generatedDir "Baked.cs") -Encoding utf8

# 1. mod release package -------------------------------------------------------
& (Join-Path $PSScriptRoot "package-mod.ps1") -GwyfRefs $GwyfRefs -OutDir $OutDir -Configuration "Release"
if ($LASTEXITCODE -ne 0) { throw "mod package build failed" }

$modZip = Get-ChildItem -LiteralPath $OutDir -Filter "GWYFCommunityNetwork-*.zip" |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
if ($null -eq $modZip) { throw "no mod release zip produced" }
Write-Host "Mod package: $($modZip.Name) ($([math]::Round($modZip.Length / 1KB)) KB)"

# 2. embed into the setup project ---------------------------------------------
$assetDir = Join-Path $repoRoot "installer\GWYFCommunityNetwork.Setup\Assets"
New-Item -ItemType Directory -Force -Path $assetDir | Out-Null
$asset = Join-Path $assetDir "mod-release.zip"
Copy-Item -LiteralPath $modZip.FullName -Destination $asset -Force

# 3. build the setup exe --------------------------------------------------------
Write-Host "Building setup exe $Version (endpoint: $endpoint)"
& dotnet build $setupProject -c Release -p:Version=$Version -v:minimal
if ($LASTEXITCODE -ne 0) { throw "setup build failed" }

$built = Join-Path $repoRoot "installer\GWYFCommunityNetwork.Setup\bin\Release\net48\GWYF-Community-Setup.exe"
if (-not (Test-Path -LiteralPath $built)) { throw "missing build output: $built" }

# 4. emit the artifact ----------------------------------------------------------
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$artifact = Join-Path $OutDir "GWYF-Community-Setup-$Version.exe"
Copy-Item -LiteralPath $built -Destination $artifact -Force

$sha = (Get-FileHash -LiteralPath $artifact -Algorithm SHA256).Hash.ToLowerInvariant()
$size = [math]::Round((Get-Item -LiteralPath $artifact).Length / 1MB, 1)
Write-Host "Done: $artifact ($size MB)"
Write-Host "SHA-256: $sha"
Write-Host "Endpoint baked: $endpoint"

# sanity: the exe must be self-validating
Write-Host "Running embedded selftest..."
& $artifact --selftest
if ($LASTEXITCODE -ne 0) { throw "setup selftest failed" }
Write-Host "Selftest PASS. Artifact ready."