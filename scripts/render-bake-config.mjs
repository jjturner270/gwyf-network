// Render static-build step: bake the production API origin into the radar page.
// Runs only when API_BASE_URL is set; otherwise leaves the checked-in dev
// default (loopback) untouched so local use is unaffected.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps", "web", "src", "config.js");
const raw = process.env.API_BASE_URL ?? "";

if (!raw) {
  console.log("[render-bake-config] API_BASE_URL unset; leaving apps/web/src/config.js as the dev default");
  process.exit(0);
}

const url = new URL(raw);
const canonical = `${url.protocol}//${url.host}`;
const body = [
  "// Generated by scripts/render-bake-config.mjs during the Render static build.",
  "// The public radar page talks to this API origin; the dev default is loopback.",
  `window.GWYF_API_BASE_URL = "${canonical}";`,
  "",
].join("\n");

writeFileSync(target, body, "utf8");
console.log(`[render-bake-config] baked ${canonical} into apps/web/src/config.js`);